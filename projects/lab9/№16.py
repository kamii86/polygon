#(№16) Найти сумму чисел главной диагонали матрицы

import numpy as np

# Вводим количество строк и столбцов
# Если матрица не квадратная, то главной диагональю будет пересечение строк и столбцов с одинаковыми индексами
rows = int(input("Введите количество строк матрицы: "))
cols = int(input("Введите количество столбцов матрицы: "))

# Ввод элементов матрицы
matrix = []
print(f"Введите элементы матрицы {rows} x {cols}:")
for i in range(rows):
    row = list(map(int, input(f"Введите элементы {i + 1}-й строки через пробел: ").split()))
    matrix.append(row)

# Преобразуем в numpy массив
matrix = np.array(matrix)

# Находим минимальное значение из числа строк и столбцов
diagonal_elements = [matrix[i][i] for i in range(min(rows, cols))]

# Вычисляем сумму элементов на главной диагонали
diagonal_sum = sum(diagonal_elements)

#Выводим результат
print(f"Сумма элементов на главной диагонали: {diagonal_sum}")
