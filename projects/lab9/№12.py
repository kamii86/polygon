#(№12)Найти длину самой длинной подпоследовательности одинаковых элементов в массиве

import numpy as np

# Ввод массива пользователем
input_data = input("Введите элементы массива через пробел: ")

#Разделяем на отдельные элементы и преобразуем в целые числа
arr = np.array(list(map(int, input_data.split())))

# Находим индексы, где элементы массива меняются
changes = np.where(arr[:-1] != arr[1:])[0]

# Добавляем начало и конец массива
lengths = np.diff(np.append(np.append(-1, changes), len(arr) - 1))

# Находим максимальную длину
max_length = np.max(lengths)

#Выводим результат
print(f"Длина самой длинной последовательности одинаковых элементов: {max_length}")
